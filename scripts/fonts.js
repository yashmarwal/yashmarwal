// Downloads the Google Fonts this site uses (latin subset only) into /fonts and writes css/fonts.css.
// Usage: node scripts/fonts.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const sources = [
  ['https://fonts.googleapis.com/css2?family=Libre+Franklin:wght@600;700&family=Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,500;0,6..72,600;1,6..72,400&family=Space+Mono:wght@400;700&family=Source+Serif+4:ital,opsz,wght@0,8..60,400;0,8..60,600;1,8..60,400&display=swap', 'latin'],
  ['https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,400,0,0&icon_names=arrow_outward,check_circle,close,menu&display=block', null],
];

(async () => {
  fs.rmSync(path.join(root, 'fonts'), { recursive: true, force: true });
  fs.mkdirSync(path.join(root, 'fonts'), { recursive: true });
  const used = new Set();
  let css = '/* Self-hosted fonts (generated by scripts/fonts.js) */\n';
  for (const [url, subset] of sources) {
    const text = await (await fetch(url, { headers: { 'User-Agent': UA } })).text();
    const blocks = [...text.matchAll(/(?:\/\*\s*([\w-]+)\s*\*\/\s*)?(@font-face\s*\{[^}]*\})/g)].map((m) => ({ subset: m[1], face: m[2] }));

    // Variable fonts come back as one identical file per weight: keep one file and one @font-face with a weight range.
    const groups = new Map();
    for (const b of blocks) {
      if (subset && b.subset !== subset) continue;
      const family = b.face.match(/font-family:\s*'([^']+)'/)[1];
      const style = (b.face.match(/font-style:\s*(\w+)/) || [])[1] || 'normal';
      const weight = +(b.face.match(/font-weight:\s*(\d+)/) || [])[1] || 400;
      const src = b.face.match(/url\((https:[^)]+)\)/)[1];
      const key = family + '|' + style + '|' + src;
      if (!groups.has(key)) groups.set(key, { family, style, src, weights: [], face: b.face });
      groups.get(key).weights.push(weight);
    }
    for (const g of groups.values()) {
      const lo = Math.min(...g.weights);
      const hi = Math.max(...g.weights);
      let name = g.family.toLowerCase().replace(/\s+/g, '-') + (g.style === 'italic' ? '-italic' : '') + (subset ? '-' + subset : '') + '.woff2';
      if (used.has(name)) name = name.replace('.woff2', '-' + lo + '.woff2'); // same family and style, different file (static weights)
      used.add(name);
      const buf = Buffer.from(await (await fetch(g.src)).arrayBuffer());
      fs.writeFileSync(path.join(root, 'fonts', name), buf);
      const weight = lo === hi ? String(lo) : lo + ' ' + hi;
      css += g.face
        .replace(/url\(https:[^)]+\)/, 'url(/fonts/' + name + ')')
        .replace(/font-weight:\s*[\d ]+;/, 'font-weight: ' + weight + ';')
        .replace(/\n\s*/g, ' ')
        .replace(/;\s*\}/, '; }') + '\n';
      console.log(name, buf.length, 'bytes, weights', weight);
    }
  }
  fs.writeFileSync(path.join(root, 'css', 'fonts.css'), css);
  console.log('wrote css/fonts.css');
})();
